  const mode = variant.key;
  const path = `${root}themes/wayfindr-${mode}-color-theme.json`;
  const content = JSON.stringify(makeTheme(variant), null, 2) + '\n';
  if (check) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`${mode} is out of date; run npm run build`);
  } else {
    await writeFile(path, content);
  }
  console.log(`${check ? 'Checked' : 'Built'} Wayfindr ${mode}`);
